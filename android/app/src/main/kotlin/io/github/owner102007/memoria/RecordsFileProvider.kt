package io.github.owner102007.memoria

import androidx.core.content.FileProvider

/**
 * Поставщик файлов для архивов записей сессии (SNO-F-REC-06).
 *
 * Через него архив из папки `Записи/` уходит системному окну
 * «Поделиться» ссылкой `content://`: чужое приложение получает право
 * прочитать один файл, а не путь в данные приложения.
 *
 * Свой класс, а не сам `FileProvider`, — чтобы в манифесте у него было
 * своё имя: два поставщика с одним именем класса в одном приложении
 * не уживаются, а готовый `FileProvider` может объявить любой пакет.
 *
 * Объявлен только в манифестах сборок ветвей СНО2026
 * (`src/sno2026core`, `src/sno2026test`) вместе с папкой, которую ему
 * можно отдавать (`res/xml/sno_records_paths.xml`). В основном
 * приложении его нет: записей там не бывает.
 */
class RecordsFileProvider : FileProvider()
