/// Разбор перечислений, прочитанных из базы.
///
/// В базе лежат имена значений, а не порядковые номера: номер молча
/// меняется при вставке нового значения в середину перечисления, и данные
/// пользователя тихо становятся другими. Имя так сломать нельзя.
///
/// Неизвестное имя не считается ошибкой: файл базы мог приехать
/// с устройства, где стоит более новая версия приложения. Такой случай
/// разумнее пережить со значением по умолчанию, чем упасть.
T enumByName<T extends Enum>(List<T> values, String? name, T fallback) {
  if (name == null) {
    return fallback;
  }
  for (final T value in values) {
    if (value.name == name) {
      return value;
    }
  }
  return fallback;
}
