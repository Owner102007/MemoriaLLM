/// Нажатия, которые забрал слой поверх экрана.
///
/// Слой, стоящий выше навигатора, может выиграть нажатие в споре
/// жестов: так точка записи сборок ветвей СНО2026 забирает себе
/// удержание (SNO-F-REC-01). Распознаватели экрана под слоем узнают об
/// этом сами — арена им отказывает. Но нажатие по странице книги
/// узнаётся мимо арены, по сырым событиям указателя (BUG-37), и о
/// проигранном споре не знает: отпущенный палец перелистнул бы
/// страницу. Здесь слой и говорит: это нажатие уже не страницы.
///
/// Записей в основном приложении никто не делает: слоя над навигатором
/// в нём нет.
abstract final class ClaimedPointers {
  static final Set<int> _claimed = <int>{};

  /// Нажатие указателя [pointer] забрано слоем.
  static void claim(int pointer) => _claimed.add(pointer);

  /// Забрано ли нажатие указателя [pointer].
  static bool contains(int pointer) => _claimed.contains(pointer);

  /// Нажатие указателя [pointer] кончилось: помнить о нём незачем.
  static void release(int pointer) => _claimed.remove(pointer);
}
