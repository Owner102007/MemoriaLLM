/// Точная арифметика карты книг (F-MAP-02, ALG-MAP-06).
///
/// Карта обязана быть одной и той же на телефоне и на ПК: участники
/// исследования видят одну библиотеку, и расположение книг на ней —
/// предмет измерения. Сложение, вычитание, умножение, деление и
/// квадратный корень в IEEE 754 дают один и тот же результат на любом
/// процессоре. Логарифм, степень и синус — нет: их считает библиотека
/// платформы, и последний бит у неё свой. Поэтому в расчёте карты
/// степеней и тригонометрии нет вовсе, логарифм — свой, а случайные
/// числа даёт свой генератор: `Random(seed)` из `dart:math` не обещан
/// одинаковым между версиями Dart.
///
/// Обе функции сверены с другой реализацией — `tool/make_map_goldens.py`.
library;

/// Генератор случайных чисел карты — Mulberry32.
///
/// Тридцать два бита состояния, одно сложение, два умножения и сдвиги:
/// достаточно для выбора случайной книги и начального разброса точек, и
/// повторяется дословно на любом языке.
class MapRandom {
  /// Создаёт генератор с зерном [seed].
  MapRandom(int seed) : _state = seed & _mask;

  static const int _mask = 0xFFFFFFFF;

  int _state;

  /// Следующее целое от 0 до 2³² − 1.
  int next() {
    _state = (_state + 0x6D2B79F5) & _mask;
    int t = _state;
    t = _multiply(t ^ (t >> 15), t | 1);
    t ^= (t + _multiply(t ^ (t >> 7), t | 61)) & _mask;
    return (t ^ (t >> 14)) & _mask;
  }

  /// Следующее число от нуля до единицы, единица не включена.
  double unit() => next() / 4294967296.0;

  /// Следующее целое от нуля до [limit], [limit] не включён.
  int below(int limit) => next() % limit;

  /// Умножение по модулю 2³².
  ///
  /// Оба сомножителя меньше 2³², произведение не помещается в 64 бита
  /// со знаком и заворачивается — но младшие 32 бита при этом верны, а
  /// нужны только они.
  static int _multiply(int a, int b) => (a * b) & _mask;
}

const double _ln2 = 0.6931471805599453;

/// Натуральный логарифм одними точными операциями.
///
/// Число приводится к отрезку от единицы до двух умножением на степень
/// двойки (оно точное), а логарифм остатка берётся рядом для
/// `2·atanh((m − 1)/(m + 1))` — двадцать слагаемых, схемой Горнера.
/// Расходится со `log` из `dart:math` не больше чем на несколько единиц
/// последнего разряда, зато одинаков везде.
///
/// Для нуля, отрицательных и бесконечности возвращает ноль: вес слова
/// по такому числу не считают.
double lnExact(double x) {
  if (!(x > 0) || x.isInfinite) {
    return 0;
  }
  int exponent = 0;
  double mantissa = x;
  while (mantissa >= 2.0) {
    mantissa *= 0.5;
    exponent++;
  }
  while (mantissa < 1.0) {
    mantissa *= 2.0;
    exponent--;
  }
  final double z = (mantissa - 1.0) / (mantissa + 1.0);
  final double z2 = z * z;
  double total = 0.0;
  for (int k = 39; k >= 1; k -= 2) {
    total = total * z2 + 1.0 / k;
  }
  return 2.0 * z * total + exponent * _ln2;
}
