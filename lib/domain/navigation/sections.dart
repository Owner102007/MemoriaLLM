/// Разделы главной навигации и то, где она стоит (F-APP-02).
///
/// Здесь только правила: какие разделы есть, где стоит навигация при
/// данной ширине окна и куда ведёт «назад». Виджеты — в `ui/app.dart`.
library;

/// Раздел приложения.
///
/// Порядок значений — порядок в навигации. «Галактика» сюда придёт
/// вместе с картой (F-MAP-06): раздел без содержимого был бы кнопкой в
/// никуда.
///
/// Не каждая сборка показывает все разделы: какие из них есть, решает
/// [sectionsFor].
enum AppSection {
  /// Полка: книги читателя по категориям.
  shelf,

  /// Устройство: все PDF, которые нашлись на диске.
  device,

  /// Тестирование: инструменты исследования в сборках ветвей СНО2026
  /// (SNO-F-CFG-03). В основном приложении раздела нет.
  testing,

  /// Настройки.
  settings,
}

/// Разделы сборки, в порядке навигации.
///
/// [scanner] — есть ли в сборке раздел «Устройство» со сканером;
/// [testing] — есть ли раздел «Тестирование». Основное приложение:
/// «Полка · Устройство · Настройки». Ветвь СНО2026: «Полка ·
/// Тестирование · Настройки» — книг на устройстве она не ищет
/// (SNO-F-CFG-02, SNO-DIV-02); архив с литературой ищет раздел
/// «Тестирование» (SNO-F-LIT-03).
///
/// Аргументы — простые признаки, а не флаги ветви: правило о разделах
/// не должно знать, откуда признак взялся, и проверяется на всех
/// сочетаниях одним прогоном тестов.
List<AppSection> sectionsFor({required bool scanner, required bool testing}) {
  return <AppSection>[
    AppSection.shelf,
    if (scanner) AppSection.device,
    if (testing) AppSection.testing,
    AppSection.settings,
  ];
}

/// Где стоит главная навигация.
enum NavPlacement {
  /// Панель у нижнего края — телефон и узкое окно.
  bottom,

  /// Полоса у верхнего края — широкое окно.
  top,
}

/// С какой ширины окна навигация встаёт наверх.
///
/// Порог тот же, что у панели поиска рядом со страницей
/// (`domain/reading/search_dock.dart`): «широкое окно» в приложении
/// значит одно и то же везде. Наверх — потому что туда же встанут
/// вкладки книг (F-DESK-01): разделы занимают левый край полосы,
/// настройки — правый, середина остаётся вкладкам.
const double kTopNavWidth = 900;

/// Где стоит навигация в окне шириной [width].
NavPlacement navPlacementFor(double width) {
  return width >= kTopNavWidth ? NavPlacement.top : NavPlacement.bottom;
}

/// Куда ведёт системное «назад» из раздела [current].
///
/// Из любого другого раздела — на «Полку»: она главный раздел, и
/// читатель, нажавший «назад», ждёт именно её. С «Полки» идти некуда —
/// `null`, приложение закрывается, как и прежде.
AppSection? sectionBehind(AppSection current) {
  return current == AppSection.shelf ? null : AppSection.shelf;
}

/// Название раздела в навигации.
String sectionTitle(AppSection section) {
  return switch (section) {
    AppSection.shelf => 'Полка',
    AppSection.device => 'Устройство',
    AppSection.testing => 'Тестирование',
    AppSection.settings => 'Настройки',
  };
}
