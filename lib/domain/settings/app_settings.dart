/// Ключи локальных настроек приложения.
///
/// Значения ключей менять нельзя без миграции: они лежат в базе на
/// устройствах пользователей.
abstract final class SettingsKeys {
  /// Выбранная тема оформления.
  static const String theme = 'ui.theme';

  /// Положение экрана при чтении: `portrait` или `landscape`.
  ///
  /// Настройка устройства, а не книги: деление страницы на полосы
  /// увеличивает текст только на широком экране, и приложение
  /// поворачивается само, не полагаясь на автоповорот системы — тот у
  /// многих выключен насовсем.
  static const String readingRotation = 'ui.reading_rotation';

  /// Как листается книга: `continuous` или `paged`.
  static const String pageFlow = 'ui.page_flow';

  /// Заперт ли масштаб страницы: `true`/`false`.
  ///
  /// Заперт — щипок и перетаскивание выключены, страница стоит там, где
  /// её положила раскладка. Отперт — страница двигается и масштабируется
  /// как в обычном просмотрщике и остаётся в этом состоянии.
  static const String zoomLock = 'ui.zoom_lock';

  /// Порядок книг на полке: имя значения [ShelfSort].
  ///
  /// Настройка устройства, а не библиотеки: на телефоне удобно видеть
  /// сначала недавние, на ПК — разложенное по названиям.
  static const String shelfSort = 'ui.shelf_sort';

  /// Какой версией правила «есть ли текст» проверены файлы устройства
  /// (F-DEV-13): число, см. `kTextLayerRule`.
  ///
  /// Настройка устройства и служебная: читатель её не видит. Список
  /// файлов живёт только здесь — и отметка о том, каким правилом он
  /// проверен, живёт рядом с ним.
  static const String deviceTextRule = 'device.text_rule';

  /// Показывать ли страницу сразу, грубо, а резкость дорисовывать
  /// следом: `true`/`false` (F-READ-02).
  ///
  /// Настройка устройства: раздражает ли ступенька «грубо → резко»,
  /// зависит от экрана и глаз, а не от книги.
  static const String pagePreview = 'reading.page_preview';

  /// Сколько соседних листов держать наготове с каждой стороны: `0`,
  /// `1` или `2` (F-READ-02).
  ///
  /// Настройка устройства: это вопрос памяти, а она у телефона и у ПК
  /// разная. Пока ключа нет, действует значение по умолчанию для
  /// платформы.
  static const String pageReserve = 'reading.page_reserve';

  /// Листать ли кнопками громкости: `true`/`false` (F-READ-26).
  ///
  /// Настройка устройства: кнопки громкости есть у телефона, и привычка
  /// листать ими — у того, кто держит его в руке.
  static const String volumeKeys = 'reading.volume_keys';

  /// Листает ли кнопка «тише» вперёд: `true`/`false` (F-READ-26).
  ///
  /// Иначе вперёд листает «громче». Настройка устройства: какая кнопка
  /// лежит под пальцем, зависит от телефона и руки.
  static const String volumeDownForward = 'reading.volume_down_forward';

  /// Развёрнуто ли чтение во весь экран: `true`/`false` (F-READ-35).
  ///
  /// Настройка устройства: окно есть только у ПК, и разворачивать его
  /// или нет, читатель решает за этим монитором, а не за книгой.
  static const String readingFullScreen = 'reading.full_screen';

  /// Ширина зоны листания с каждой стороны экрана, целым числом
  /// процентов: `30` (F-READ-23).
  ///
  /// Настройка устройства: до какого места экрана достаёт большой палец,
  /// зависит от телефона и руки, а не от книги.
  static const String tapZone = 'reading.tap_zone';

  /// Показана ли уже подсказка о зонах листания: `true` (F-READ-23).
  ///
  /// Подсказка появляется один раз за жизнь установки. Ключа нет — её
  /// ещё не показывали; настройки убирают ключ, чтобы показать снова.
  static const String tapZoneHintSeen = 'reading.tap_zone_hint_seen';

  /// Таблица клавиш листания на ПК (F-READ-25): запись
  /// `KeyBindings.encode`.
  ///
  /// Настройка устройства: клавиатура и педаль-листалка лежат у этого
  /// компьютера. Ключа нет — действует таблица из коробки.
  static const String turnKeys = 'reading.turn_keys';

  /// Идентификатор этого устройства для меток HLC.
  static const String nodeId = 'sync.node_id';

  /// Последняя выданная метка HLC.
  static const String lastHlc = 'sync.last_hlc';

  /// Язык, на который переводим по умолчанию (S8).
  static const String targetLanguage = 'llm.target_language';

  /// Заведены ли промпты из коробки (S6).
  ///
  /// Отметка нужна затем, чтобы «Значение» и «Перевод» не возвращались
  /// после каждого запуска к читателю, который их удалил: они обычные
  /// записи, а не код, и удаление обязано быть окончательным. Отметка
  /// **не** синхронизируется, и это правильно — заведение промптов
  /// местное дело каждого устройства, а сами промпты приедут слиянием.
  static const String promptsSeeded = 'llm.prompts_seeded';
}

/// Настройки приложения — простое хранилище «ключ-значение».
///
/// Эти настройки **не синхронизируются**: тема, выбранная для чтения
/// ночью с телефона, не должна перекрашивать ПК, а идентификатор узла
/// вообще обязан быть у каждого устройства свой.
abstract interface class AppSettingsRepository {
  /// Читает значение или `null`, если ключа нет.
  Future<String?> read(String key);

  /// Записывает значение.
  Future<void> write(String key, String value);

  /// Удаляет ключ.
  Future<void> remove(String key);

  /// Живое значение ключа.
  Stream<String?> watch(String key);
}
