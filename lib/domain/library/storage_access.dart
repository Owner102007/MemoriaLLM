/// Доступ ко всем файлам устройства.
///
/// Это самое широкое разрешение Android, и приложение, которое обещает
/// приватность, обязано объяснить его первым и своими словами. Смысл его
/// ровно один: **найти** книги там, где они лежат. Не забрать, не
/// скопировать, не отправить — найти. Всё, что приложение делает с
/// найденным, видно в исходниках: читает первую страницу для обложки,
/// читает метаданные и текст первых страниц для поиска, и хранит это
/// только на самом устройстве.
///
/// Отказ ничего не ломает. Приложение целиком остаётся работоспособным на
/// пути S5.1: книга выбирается системным диалогом по одной и читается по
/// дескриптору, без копии. Это состояние не «запасной вариант на бумаге»,
/// а первоклассное поведение, и проверяется тестами наравне с основным.
library;

/// В каком состоянии доступ к файлам устройства.
enum StorageAccessState {
  /// Разрешение не нужно вовсе: на Windows у приложения обычный доступ к
  /// файлам пользователя, и спрашивать нечего.
  notRequired,

  /// Разрешение выдано: обход устройства возможен.
  granted,

  /// Разрешения нет. Не ошибка и не тупик — просто другой способ
  /// добавлять книги.
  denied;

  /// Можно ли обходить устройство.
  bool get allowsScan =>
      this == StorageAccessState.granted ||
      this == StorageAccessState.notRequired;
}

/// Разрешение на доступ ко всем файлам и корни, с которых начинать обход.
///
/// Реализация — в `infrastructure`: на Android это канал в `MainActivity`,
/// на Windows — домашняя папка пользователя и состояние
/// [StorageAccessState.notRequired]. Тесты подставляют свою и проверяют
/// оба сценария, включая отказ.
abstract interface class StorageAccess {
  /// Текущее состояние разрешения.
  ///
  /// Спрашивается каждый раз, когда экран возвращается к жизни: читатель
  /// мог отозвать разрешение в настройках Android, пока приложение висело
  /// в фоне, и узнать об этом иначе нельзя.
  Future<StorageAccessState> state();

  /// Открывает системный экран выдачи разрешения.
  ///
  /// Возвращается сразу: ответа Android не даёт вовсе, состояние
  /// перепроверяется, когда приложение снова окажется на переднем плане.
  Future<void> request();

  /// Откуда начинать обход.
  ///
  /// На телефоне это встроенная память и карта, если она есть; на
  /// Windows — домашняя папка. Пустой список означает, что обходить
  /// нечего: разрешения нет или система не назвала ни одного корня.
  Future<List<String>> roots();
}
