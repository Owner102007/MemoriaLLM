import 'dart:async';
import 'dart:typed_data';

import 'book_file_picker.dart';
import 'book_source.dart';

/// Открытая книга, из которой можно читать куски.
///
/// Договор про [read] взят не с потолка: ровно такой колбэк ждёт PDFium
/// через `PdfDocument.openCustom`. Совпадение намеренное — иначе между
/// приложением и движком встал бы ещё один переходник, а он на каждом
/// чтении страницы копировал бы буфер.
abstract interface class BookHandle {
  /// Длина книги в байтах.
  int get length;

  /// Путь, по которому движок откроет файл сам, или `null`, если пути
  /// нет и читать надо кусками.
  ///
  /// Путь — быстрый путь, и он же единственный на Windows. Ссылка
  /// `content://` пути не имеет: у документа Android его нет вовсе.
  String? get path;

  /// Читает [size] байт с позиции [position] в начало [buffer].
  ///
  /// Возвращает, сколько байт прочитано, или `-1`, если чтение
  /// не удалось. Ноль означает конец файла.
  FutureOr<int> read(Uint8List buffer, int position, int size);

  /// Закрывает дескриптор. Вызывается ровно один раз.
  Future<void> close();
}

/// До книги не добраться: файл переехал или удалён, разрешение на ссылку
/// отозвано, карту памяти вынули.
///
/// Это не поломка приложения, а состояние: книга остаётся на полке со
/// всем, что читатель к ней написал, и ждёт, когда файл выберут заново.
class BookUnavailableException implements Exception {
  /// Создаёт исключение.
  const BookUnavailableException(this.source, {this.cause});

  /// Источник, до которого не добрались.
  final BookSource source;

  /// Исходная ошибка платформы, если она была.
  final Object? cause;

  @override
  String toString() => 'BookUnavailableException($source)';
}

/// Хранилище книг: превращает выбранный файл в источник и открывает
/// источник для чтения.
///
/// Реализаций две — обычная файловая (Windows, копии, тесты) и Android
/// поверх Storage Access Framework. Всё остальное приложение про эту
/// разницу не знает.
abstract interface class BookStorage {
  /// Заводит выбранный файл: закрепляет разрешение, а если ссылка не
  /// годится для чтения кусками — потоково копирует книгу к себе.
  ///
  /// Возвращает источник, который переживёт перезапуск приложения.
  Future<BookSource> adopt(PickedFile file);

  /// Открывает источник для чтения.
  ///
  /// Бросает [BookUnavailableException], если до книги не добраться.
  Future<BookHandle> open(BookSource source);

  /// Жив ли доступ к книге. Дешёвая проверка без открытия файла.
  Future<bool> available(BookSource source);

  /// Отпускает источник, когда книгу снимают с полки: удаляет **свою**
  /// копию и освобождает закреплённое разрешение.
  ///
  /// Чужой файл не трогается никогда. Разрешения освобождать нужно
  /// потому, что Android держит их ограниченное число на приложение.
  Future<void> release(BookSource source);
}
