import 'dart:math';

/// Идентификатор книги или категории: UUID-подобная строка из случайных
/// байтов.
///
/// Пакет ради генерации шестнадцати байт не подключается: пользы от него
/// здесь на одну строку, а в открытом проекте каждая зависимость — это
/// ещё и лицензия, которую придётся объяснять.
///
/// Случайность берётся у системы (`Random.secure`), а не у обычного
/// генератора: эти идентификаторы поедут в синхронизацию, и совпадение
/// у двух устройств означало бы слипшиеся книги.
String newLibraryId() {
  final StringBuffer buffer = StringBuffer();
  for (int i = 0; i < 16; i++) {
    buffer.write(_random.nextInt(256).toRadixString(16).padLeft(2, '0'));
    if (i == 3 || i == 5 || i == 7 || i == 9) {
      buffer.write('-');
    }
  }
  return buffer.toString();
}

final Random _random = Random.secure();
