/// Подпись блока полки: название книги и «Добавить книги» (BUG-14).
///
/// Подпись стоит под обложкой, внутри участка категории, а участок
/// закрашен узором. Спокойный узор подписи не мешает — он покрашен почти
/// в цвет подложки. Кислотный рисуется неоном, и против неоновой линии
/// основной текст темы даёт контраст около единицы: буква, через которую
/// прошла линия, не читается вовсе.
///
/// Поэтому у подписи **своя непрозрачная подложка**, как у метки «скан»
/// (F-DEV-13): под буквами лежит поверхность темы, а не узор. Узор
/// остаётся виден между блоками и по краям участка — категорию
/// по-прежнему узнают взглядом.
library;

import '../theme/app_palette.dart';

/// Кегль подписи.
const double kShelfCaptionFontSize = 11;

/// Высота места под текст подписи: две строки этим кеглем.
const double kShelfCaptionTextHeight = 30;

/// Отступ подписи от обложки.
const double kShelfCaptionGap = 4;

/// Поля подложки вокруг текста: по горизонтали и по вертикали.
const double kShelfCaptionPadX = 4;

/// См. [kShelfCaptionPadX].
const double kShelfCaptionPadY = 1;

/// Сколько высоты блока занимает подпись вместе с отступом от обложки.
///
/// Ровно столько же, сколько занимала прежняя, без подложки: размер
/// обложки от починки не изменился.
const double kShelfCaptionExtent =
    kShelfCaptionGap + kShelfCaptionTextHeight + kShelfCaptionPadY * 2;

/// Цвета подписи: её собственная подложка и текст на ней.
///
/// Подложка — поверхность темы, а не цвет категории: пару «поверхность и
/// основной текст» держит сама тема, и автотест тем проверяет её порогом
/// 4,5:1. Оттенок категории сюда не подмешивается намеренно — иначе
/// читаемость подписи снова зависела бы от названия категории.
({int background, int text}) shelfCaptionColors(AppPalette palette) {
  return (background: palette.surface, text: palette.text);
}
