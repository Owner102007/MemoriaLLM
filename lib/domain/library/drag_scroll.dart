/// Самопрокрутка полки, пока книгу несут пальцем.
///
/// Книгу переносят в категорию, которой не видно, — значит, у краёв экрана
/// полка обязана ехать сама. Первая версия отводила под это 90 точек у
/// каждого края и одну скорость на всю полосу, и на телефоне это оказалось
/// неудобно вдвойне: попасть пальцем в узкую полосу трудно, а попав, книга
/// сразу уносилась на всю скорость (замечание владельца, 28.08.2026).
///
/// Теперь у каждого края **две** зоны. Внешняя — быстрая: до неё
/// добираются, когда надо перебросить книгу через несколько категорий, и
/// там палец и так уже у самого края экрана. Внутренняя — медленная:
/// в неё попадают, когда нужный участок почти виден и полку надо лишь
/// подвинуть. Между зонами скорость не прыгает, а переходит: рывок под
/// пальцем ощущается поломкой сильнее, чем слишком быстрая прокрутка.
///
/// Расчёт живёт в `domain`, потому что это чистая арифметика: он
/// проверяется обычным юнит-тестом, без экрана, жестов и таймеров.
library;

import 'dart:math' as math;

/// Доля высоты области показа, отведённая под чувствительную полосу
/// у каждого края.
///
/// 22 % на телефоне высотой 2400 точек — это примерно 500 точек, то есть
/// пятая часть экрана вместо прежних 90 точек (меньше четырёх процентов).
const double kDragScrollSlowZone = 0.22;

/// Доля высоты под быстрой зоной — она лежит **внутри** медленной,
/// вплотную к краю.
const double kDragScrollFastZone = 0.09;

/// Нижняя граница чувствительной полосы в точках.
///
/// На коротком окне ПК доля выродилась бы в несколько точек, и полка
/// перестала бы ехать вовсе.
const double kDragScrollMinZone = 56;

/// Верхняя граница чувствительной полосы в точках.
///
/// На высоком мониторе доля дала бы полосу в полтысячи точек с лишним:
/// середина экрана осталась бы уже, чем зоны по краям.
const double kDragScrollMaxZone = 260;

/// Какую долю высоты зонам нельзя занимать даже вместе.
///
/// Верхняя и нижняя полосы обязаны оставить между собой спокойную
/// середину: иначе на низком окне полка едет всегда и остановить её
/// нечем.
const double kDragScrollNeutralShare = 0.35;

/// Скорость в медленной зоне, точек в секунду.
///
/// Примерно четверть экрана телефона за секунду: читатель успевает
/// увидеть, куда приехала полка, и остановиться там, где нужно.
const double kDragScrollSlowSpeed = 260;

/// Скорость в быстрой зоне у самого края, точек в секунду.
///
/// Полка длиной в десяток категорий проезжается за пару секунд.
const double kDragScrollFastSpeed = 1900;

/// Границы зон для области показа высотой [height].
///
/// Возвращает `(медленная, быстрая)` в точках, считая от края.
({double slow, double fast}) dragScrollZones(double height) {
  if (!height.isFinite || height <= 0) {
    return (slow: 0.0, fast: 0.0);
  }
  final double room = height * kDragScrollNeutralShare;
  final double wanted = height * kDragScrollSlowZone;
  // Сначала доля, потом упоры в точках, и только потом — запрет занимать
  // середину. Порядок важен: на низком окне побеждает именно середина,
  // иначе нижний упор растянул бы зоны на весь экран.
  final double bounded = math.min(
    math.max(wanted, kDragScrollMinZone),
    kDragScrollMaxZone,
  );
  final double slow = math.min(bounded, room);
  // Быстрая зона всегда меньше медленной: иначе «быстро» начиналось бы
  // раньше «медленно», и медленной не было бы вовсе.
  final double fast = math.min(height * kDragScrollFastZone, slow * 0.55);
  return (slow: slow, fast: math.max(0.0, fast));
}

/// Скорость самопрокрутки в точках за секунду.
///
/// [y] — палец по вертикали внутри **самой полки**, [height] — её высота.
/// Мерить от края экрана нельзя: сверху стоит панель приложения, и зона,
/// отсчитанная от экрана, уходила бы под неё — быстрой половины у верхнего
/// края не существовало бы вовсе.
/// Отрицательная скорость везёт полку к началу списка, положительная —
/// к концу. Ноль — палец в спокойной середине.
///
/// Палец, уехавший за край экрана, считается прижатым к самому краю:
/// прокрутка там обязана идти на полной скорости, а не выключаться.
double dragScrollSpeed({required double y, required double height}) {
  if (!y.isFinite || !height.isFinite || height <= 0) {
    return 0.0;
  }
  final ({double slow, double fast}) zones = dragScrollZones(height);
  if (zones.slow <= 0) {
    return 0.0;
  }
  final double fromTop = y;
  final double fromBottom = height - y;
  // Ближний край и решает. На низком окне обе зоны могут дотянуться до
  // пальца разом — тогда побеждает тот край, к которому палец ближе.
  if (fromTop <= fromBottom) {
    return -_speedAt(fromTop, zones);
  }
  return _speedAt(fromBottom, zones);
}

/// Самопрокрутка одного переноса: та же скорость, но с предохранителем.
///
/// Зона занимает пятую часть полки, и книга, поднятая из верхнего или
/// нижнего ряда, оказывается в ней **сразу же**: читатель ещё ничего не
/// попросил, а полка уже поехала и увезла книгу от того места, откуда её
/// взяли. При прежней зоне в 90 точек этого почти не случалось, при
/// нынешней случается каждый раз (замечание владельца, 29.08.2026).
///
/// Поэтому зона включается не раньше, чем палец **однажды побывал в
/// спокойной середине**. Книгу взяли из середины и повели к краю —
/// предохранитель снят с первого же движения, то есть в обычном случае
/// его как бы и нет. Книгу взяли у самого края — полка стоит, пока
/// читатель не сходит к середине и не вернётся: одно лишнее движение
/// против полки, уезжающей сама собой.
///
/// Состояние живёт ровно один перенос: на каждое поднятие книги заводится
/// новый замок.
class DragScrollGate {
  bool _armed = false;

  /// Снят ли предохранитель.
  bool get armed => _armed;

  /// Скорость самопрокрутки с учётом предохранителя.
  ///
  /// Значения те же, что у [dragScrollSpeed]; отличие одно — пока палец
  /// не побывал в спокойной середине, ответ всегда ноль.
  double speedAt({required double y, required double height}) {
    final double speed = dragScrollSpeed(y: y, height: height);
    if (speed == 0) {
      _armed = true;
    }
    return _armed ? speed : 0.0;
  }
}

/// Скорость по расстоянию до края — общая для верха и низа.
double _speedAt(double distance, ({double slow, double fast}) zones) {
  if (distance >= zones.slow) {
    return 0.0;
  }
  if (distance <= zones.fast) {
    // Быстрая зона: у самого края — полная скорость, у её внутренней
    // границы — ровно медленная. Скорость нигде не прыгает.
    if (zones.fast <= 0) {
      return kDragScrollFastSpeed;
    }
    final double t = math.max(0.0, distance) / zones.fast;
    return kDragScrollFastSpeed +
        (kDragScrollSlowSpeed - kDragScrollFastSpeed) * t;
  }
  // Медленная зона: у внутренней границы — ноль, у быстрой — медленная
  // скорость целиком.
  final double span = zones.slow - zones.fast;
  if (span <= 0) {
    return kDragScrollSlowSpeed;
  }
  final double t = (zones.slow - distance) / span;
  return kDragScrollSlowSpeed * t;
}
