/// Честная пометка скана без текста (F-DEV-13).
///
/// Слова и цвета пометки живут в одном месте: её видят на обложке на
/// полке, на карточке в «Устройстве», в меню книги и в сообщении при
/// добавлении — и везде она обязана говорить одно и то же.
library;

import '../theme/app_palette.dart';

/// Слово на обложке.
const String kScanMark = 'скан';

/// То же полными словами — строкой в меню книги и для экранного диктора.
const String kScanLong = 'скан без текстового слоя';

/// Что это значит — подсказкой у метки и строкой при добавлении.
const String kScanExplanation =
    'текст не распознан — выделение, поиск и функции '
    'в этой книге не работают';

/// Цвета метки: её собственная подложка и текст на ней.
///
/// Подложка **непрозрачная**: метка лежит на обложке, а обложка бывает
/// любой — белой, чёрной, пёстрой. На полупрозрачной подложке слово
/// читалось бы на одной обложке и терялось на другой. Пара «поверхность
/// и основной текст» держит 4,5:1 на каждой теме — это проверяет
/// автотест тем, и тот же порог проверен у самой метки.
({int background, int text}) scanMarkColors(AppPalette palette) {
  return (background: palette.surface, text: palette.text);
}

/// Пометить ли книгу сканом по её признаку текстового слоя.
///
/// Только твёрдое «текста нет»: «не знаю» (`null`) меткой не становится —
/// книгу, которую не удалось прочесть, сканом не называют.
bool isMarkedScan(bool? hasTextLayer) => hasTextLayer == false;
