/// Выбранный человеком файл.
class PickedFile {
  /// Создаёт описание файла.
  const PickedFile({required this.path, required this.name});

  /// Путь, по которому файл можно открыть на этом устройстве.
  ///
  /// На Android это может быть путь к копии в кэше приложения, а не
  /// исходный файл: система отдаёт документ по `content://`, и настоящего
  /// пути к нему у приложения нет. Для чтения это ничего не меняет,
  /// а вот S5, где книга остаётся в библиотеке надолго, обязана это учесть.
  final String path;

  /// Имя файла с расширением.
  final String name;
}

/// Диалог выбора PDF средствами системы.
///
/// Интерфейс прячет платформенную разницу: на Android это System Access
/// Framework, на Windows — обычный диалог открытия файла. Тесты
/// подставляют сюда заглушку и обходятся без диалога вовсе.
abstract interface class BookFilePicker {
  /// Показывает диалог выбора PDF.
  ///
  /// Возвращает `null`, если человек закрыл диалог, ничего не выбрав.
  Future<PickedFile?> pickPdf();
}
