/// Выбранный человеком файл — ровно то, что вернул системный диалог,
/// и ничего сверх этого.
///
/// Диалог не читает файл и не копирует его: на Android он отдаёт имя и
/// ссылку `content://`, на Windows — имя и путь. Превращение выбранного
/// в источник, который переживёт перезапуск, — дело `BookStorage`.
class PickedFile {
  /// Создаёт описание файла.
  ///
  /// Хотя бы одно из [path] и [uri] обязано быть заполнено: выбор, из
  /// которого не следует, где лежит файл, бессмыслен.
  const PickedFile({required this.name, this.path, this.uri})
    : assert(path != null || uri != null, 'нужен путь или ссылка');

  /// Имя файла с расширением.
  final String name;

  /// Путь на диске, если он есть. На Android его нет: система отдаёт
  /// документ по ссылке, а настоящего пути к нему приложение не знает.
  final String? path;

  /// Ссылка `content://`, если файл пришёл через Storage Access
  /// Framework.
  final String? uri;

  @override
  String toString() => 'PickedFile($name, path: $path, uri: $uri)';
}

/// Диалог выбора PDF средствами системы.
///
/// Интерфейс прячет платформенную разницу: на Android это Storage Access
/// Framework, на Windows — обычный диалог открытия файла. Тесты
/// подставляют сюда заглушку и обходятся без диалога вовсе.
abstract interface class BookFilePicker {
  /// Показывает диалог выбора PDF.
  ///
  /// Возвращает `null`, если человек закрыл диалог, ничего не выбрав.
  Future<PickedFile?> pickPdf();
}
