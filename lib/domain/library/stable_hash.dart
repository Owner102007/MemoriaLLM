/// Устойчивый хеш строки — FNV-1a, 32 бита.
///
/// `String.hashCode` для этого не годится: он не обещан одинаковым между
/// запусками, платформами и версиями Dart. А нам нужно ровно обещание:
/// вид категории обязан быть одним и тем же на телефоне и на ПК, а имя
/// файла обложки — не меняться от запуска к запуску, иначе кэш каждый раз
/// начинается заново. Своя реализация в двадцать строк дешевле
/// зависимости и проверяется таблицей значений
/// (`tool/make_category_goldens.py`).
int stableHash(String value) {
  int hash = 0x811C9DC5;
  for (final int code in value.runes) {
    hash = _step(hash, code & 0xFFFF);
    if (code > 0xFFFF) {
      hash = _step(hash, (code >> 16) & 0xFFFF);
    }
  }
  return hash;
}

/// Один шаг FNV-1a: сложение по модулю два и умножение на простое число.
///
/// Умножение на 16777619 разложено на сдвиги: прямое умножение в
/// арифметике, совместимой с JavaScript, переполняется иначе, чем на
/// устройстве, и хеш разъехался бы между платформами.
int _step(int hash, int unit) {
  final int mixed = hash ^ unit;
  return (mixed +
          (mixed << 1) +
          (mixed << 4) +
          (mixed << 7) +
          (mixed << 8) +
          (mixed << 24)) &
      0xFFFFFFFF;
}
