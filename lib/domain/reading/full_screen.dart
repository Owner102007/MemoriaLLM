/// Чтение во весь экран на ПК (F-READ-35).
///
/// На телефоне страница и так занимает весь экран: системные панели
/// спрятаны, и окна у приложения нет. На ПК окно есть — с заголовком,
/// рамкой и панелью задач под ним, — и «страница во весь экран» там
/// начинается с того, что окно занимает весь монитор.
///
/// Разворачивает окно платформа, а не Flutter: своего вызова для этого у
/// него нет. Что и когда разворачивать, решает экран чтения; здесь —
/// только договор с платформой, чтобы экран проверялся тестами без неё.
library;

/// Окно приложения, которое умеет занять весь монитор.
abstract interface class FullScreenWindow {
  /// Умеет ли платформа разворачивать окно.
  ///
  /// Где не умеет, кнопки «Во весь экран» нет вовсе: кнопка, которая
  /// заведомо ничего не сделает, хуже её отсутствия.
  bool get available;

  /// Разворачивает окно во весь экран или возвращает прежнее.
  ///
  /// `true` — окно теперь в запрошенном состоянии; `false` — платформа
  /// отказала, и окно осталось каким было.
  Future<bool> setFullScreen(bool on);
}

/// Платформа без окна: телефон и тесты.
class NoFullScreenWindow implements FullScreenWindow {
  /// Создаёт заглушку.
  const NoFullScreenWindow();

  @override
  bool get available => false;

  @override
  Future<bool> setFullScreen(bool on) async => false;
}
