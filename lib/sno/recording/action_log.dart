/// Журнал действий участника — то, что о записи знают экраны
/// (SNO-F-REC-02).
///
/// Полка, экран чтения и настройки пишут в журнал через этот договор и
/// больше о записи не знают ничего: ни как она начинается, ни где
/// лежит. В основном приложении записи нет вовсе — журнала экранам
/// никто не даёт, и ни один вызов не делается.
library;

import 'event.dart';

/// Куда экраны пишут действия участника.
abstract interface class ActionLog {
  /// Идёт ли запись. Дорогие данные события собирают, только если да.
  bool get recording;

  /// Пишет событие. Вне записи не делает ничего.
  void log(SnoEventType type, {Map<String, Object?> data});

  /// Участник перешёл на экран [name]: `shelf`, `galaxy`, `testing`,
  /// `settings`, `reader`. Экран подставляется в каждое событие; смена экрана
  /// пишется событием `nav.screen`.
  void screen(String name);

  /// Книга с отпечатком [book] открылась; [via] — каким путём её
  /// открыли: `shelf` — с полки, `shelf_search` — из найденного по
  /// названию. Отпечаток с этого мига стоит в каждом событии, а в
  /// `book.open` — ещё и номер обращения к этой книге за запись.
  void bookOpened(
    String book, {
    required String via,
    Map<String, Object?> data,
  });

  /// Книгу закрыли: `book.close` с тем, сколько она была открыта.
  /// [data] — что о закрытии знает экран: сколько книгу читали на
  /// виду за это открытие и всего (SNO-F-MAP-01).
  void bookClosed({Map<String, Object?> data});

  /// Что сейчас на экране чтения: страница и полоса с единицы, режим
  /// показа. Подставляется в каждое событие, пока книга открыта.
  void place({required int page, required int strip, required String mode});
}
