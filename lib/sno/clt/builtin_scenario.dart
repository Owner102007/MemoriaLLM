/// ориентации в источниках. Формулировки — перевод, сделанный для этого
/// теста; откуда что взято и как считается — заметка «Cognitive load
/// test — состав теста» описательной структуры.
///
/// **Версия 2** (шаг 25). Блоков нет, и вопроса об усилии после блока
/// тоже (SNO-F-REC-15, решение владельца от 06.10.2026). Перед первым
/// пунктом — экран `intro`: тест идёт после письменной работы, и
/// сказано, что оценивать. Среди пунктов — два маркера честности
/// (SNO-F-CLT-04): выглядят как остальные, в показатели не входят и
/// сверяются с записью действий — с числом отлучек и открытых книг.
///
/// **Версия 3** (правка шага 25, решение владельца АЗ от 06.10.2026).
/// Оценивается вся работа — и изучение материала, и письменная часть:
/// вступление говорит об этом и к честности впрямую не призывает. К
/// восемнадцати пунктам добавлены два пункта «шкалы лжи» — по образцу
/// шкал социальной желательности (Айзенк; Кроун и Марлоу): мелкая
/// слабость, которая есть у каждого, и достоинство, которого нет ни у
/// кого. Ключи у них противоположные: признать слабость — согласиться,
/// не приписать себе достоинство — не согласиться. Тот, кто выставляет
/// себя лучше, чем есть, получает обе отметки; тот, кто жмёт одну
/// кнопку подряд, — ровно одну; внимательный и искренний — ни одной.
/// С записью действий эти пункты не сверяются: они не о сессии.
///
/// Сценарий записан данными Dart, а не файлом ассетов: в основное
/// приложение, где теста нет, он так не попадает вовсе. Файл с тем же
/// `id` в папке данных приложения подменяет встроенный
/// (`load_test.dart`).
