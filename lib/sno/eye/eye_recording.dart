/// Айтрекер внутри записи участника — что видят участник и организатор
/// (SNO-F-EYE-01, SNO-F-EYE-02, SNO-F-EYE-06; кадры SNO-SCR-07.1,
/// SNO-SCR-07.2, SNO-SCR-07.4).
///
/// После «Код записан» на ПК с местом записи идёт калибровка — первая
/// часть записи: самопроверка, точки, фаза движения головы, слежение,
/// точки проверки и итог. Принято — «Начать», и с этого мига идут сорок
/// минут изучения (`study.start`). Не принято — повтор; после второй
/// неудачи организатор выбирает удержанием: «Писать с пометкой» или «Без
/// взгляда». Всё изучение взгляд пишется молча. Запись остановилась —
/// проверка точности в конце: девять точек той же моделью; организатор
/// может её пропустить удержанием. Потом — экран завершения.
///
/// Здесь — договор между записью айтрекера (`eye_tracker.dart`) и её
/// экраном (`recording_screen.dart`); строка «Взгляд: …» экрана
/// завершения — `recording/gaze_line.dart`. Виджетов здесь нет.
library;

import 'dart:ui' show Size;

import 'package:flutter/foundation.dart';

import 'eye_calibration_run.dart';

/// Сколько неудачных попыток калибровки до выбора организатора
/// (SNO-F-EYE-01, решение Т30): после второй — «Писать с пометкой» или
/// «Без взгляда».
const int kRecordingAttempts = 2;

/// Подсказка перед проверкой в конце записи (SNO-F-EYE-06).
const String kEndCheckIntro = 'Ещё 15 секунд — смотрите на точки';

/// Сколько держать кнопку организатора: выбор после неудачи, пропуск
/// проверки в конце.
const Duration kEyeChoiceHold = Duration(seconds: 2);

/// Где айтрекер записи сейчас.
enum EyeRecordingPhase {
  /// Самопроверка места и камера перед калибровкой.
  starting,

  /// Идут точки калибровки.
  calibrating,

  /// Итог попытки: «Начать», «Повторить» или выбор организатора.
  result,

  /// Идёт изучение: взгляд пишется, экрана айтрекера нет.
  studying,

  /// Запись остановлена — точки проверки в конце.
  endCheck,

  /// Всё кончилось: экрана айтрекера нет.
  done,
}

/// Айтрекер записи глазами экрана: что показывать и что можно нажать.
abstract interface class EyeRecordingView implements Listenable {
  /// Где он сейчас.
  EyeRecordingPhase get phase;

  /// Что идёт словами, пока калибровка готовится.
  String? get stage;

  /// Точки, которые на экране: попытка калибровки или проверка в конце.
  EyeTargetsRun? get targets;

  /// Итог последней попытки.
  EyeAttemptOutcome? get outcome;

  /// Номер последней попытки.
  int get attempt;

  /// Сколько попыток не приняты.
  int get failures;

  /// Повторять больше нельзя: организатор выбирает, писать ли взгляд.
  bool get mustChoose;

  /// Спутник поднимается заново: кнопки ждут.
  bool get busy;

  /// Что пошло не так словами — в итоге попытки; `null` — ничего.
  String? get problem;

  /// Экран сообщает, что кадр с точкой отрисован.
  abstract EyeFrameShown? frameShown;

  /// Размер окна в логических пикселях — от экрана.
  abstract Size Function()? windowSize;

  /// «Начать»: калибровка принята, пошло изучение.
  Future<void> begin();

  /// «Повторить»: ещё одна попытка (после «не видно лица» и сбоя
  /// спутника — та же, не в счёт).
  Future<void> retry();

  /// Выбор организатора после второй неудачи: [write] — писать взгляд с
  /// пометкой, иначе — без взгляда.
  Future<void> choose({required bool write});

  /// Организатор пропускает проверку в конце.
  void skipEndCheck();
}
